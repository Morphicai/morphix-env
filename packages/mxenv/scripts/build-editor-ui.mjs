// Bundles the React editor UI (src/editor-ui/client.tsx + styles.css) into a
// generated TS module so the CLI's server build can inline everything with
// zero external requests and zero runtime react dependency.
//
// Output: src/editor-ui/generated/clientAssets.ts (gitignored, regenerated
// by every `pnpm build` / `pnpm dev` / `pnpm test` via the package scripts).

import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const result = await build({
  entryPoints: [resolve(root, 'src/editor-ui/client.tsx')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['es2019'],
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'eof',
  write: false,
  logLevel: 'silent',
})

const js = result.outputFiles[0].text
const css = readFileSync(resolve(root, 'src/editor-ui/styles.css'), 'utf8')

const outDir = resolve(root, 'src/editor-ui/generated')
mkdirSync(outDir, { recursive: true })
writeFileSync(
  resolve(outDir, 'clientAssets.ts'),
  '// AUTO-GENERATED by scripts/build-editor-ui.mjs — do not edit.\n' +
    '// Inlined into the server build so the editor makes zero external requests.\n' +
    `export const EDITOR_CLIENT_JS = ${JSON.stringify(js)}\n` +
    `export const EDITOR_CLIENT_CSS = ${JSON.stringify(css)}\n`
)

console.log(
  `[editor-ui] client bundle ${(js.length / 1024).toFixed(1)} KiB, styles ${(css.length / 1024).toFixed(1)} KiB -> generated/clientAssets.ts`
)
