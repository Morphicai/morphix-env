import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const clientRoot = resolve(root, 'src/panel-ui')
const generatedDir = resolve(clientRoot, 'generated')
const cssOutput = resolve(generatedDir, 'panel.css')
const require = createRequire(import.meta.url)

const tailwindCli = resolve(dirname(require.resolve('@tailwindcss/cli/package.json')), 'dist/index.mjs')

mkdirSync(generatedDir, { recursive: true })

// Tailwind owns shadcn utilities; esbuild owns only the browser bundle.
execFileSync(process.execPath, [
  tailwindCli,
  '--input', resolve(clientRoot, 'client/index.css'),
  '--output', cssOutput,
  '--minify',
], { cwd: root, stdio: 'inherit' })

const result = await build({
  entryPoints: [resolve(clientRoot, 'client.tsx')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  jsx: 'automatic',
  alias: { '@': resolve(clientRoot, 'client') },
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
})

const css = readFileSync(cssOutput, 'utf8')
const js = result.outputFiles[0].text
const hash = createHash('sha256').update(css).update('\0').update(js).digest('hex').slice(0, 24)
const integrity = `sha256-${createHash('sha256').update(js).digest('base64')}`
const module = `// Generated by scripts/build-panel-ui.mjs. Do not edit or commit.\n` +
  `export const panelCss = ${JSON.stringify(css)}\n` +
  `export const panelJs = ${JSON.stringify(js)}\n` +
  `export const panelBundleHash = ${JSON.stringify(hash)}\n` +
  `export const panelJsIntegrity = ${JSON.stringify(integrity)}\n`

writeFileSync(resolve(generatedDir, 'clientAssets.ts'), module)
rmSync(cssOutput, { force: true })
console.log(`panel-ui: ${(js.length / 1024).toFixed(1)} KB JS + ${(css.length / 1024).toFixed(1)} KB CSS · ${hash}`)
