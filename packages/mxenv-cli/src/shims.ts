/**
 * Shim generation / stripping / two-level manifests for `shell-init` (L3).
 * The shared pure PATH/list logic (shimsDir, RESERVED_SHIM_NAMES,
 * validateShimList, stripShimsFromPath, sanitizeBootEnv) lives in
 * mxenv-core so the L2 CLI shares one implementation (package-split 4.1).
 */

/** Marks files generated by `mxenv-cli shell-init`; handmade files lack it and are never touched. */
export const SHIM_MARKER = '# mxenv shim — regenerated by `mxenv shell-init`; do not edit by hand.'
/** 0.12.x 前生成的 shim 标记：识别/剥离双认（升级后旧块不得泄漏），写侧只产新名。 */
export const LEGACY_SHIM_MARKER = '# mx-env shim — regenerated by `mx-env shell-init`; do not edit by hand.'

/** 工具生成判定（新旧双认）：无标记=手工文件，永不触碰。 */
export function isGeneratedShim(content: string): boolean {
  return content.includes(SHIM_MARKER) || content.includes(LEGACY_SHIM_MARKER)
}

/**
 * Shim body: guard against a missing mxenv (uninstall, nvm switch) with an
 * actionable message instead of a bare "command not found", then hand off to
 * `run`. The marker line identifies tool-generated shims for --remove and
 * convergence; MXENV_SHIM is read by the CLI at boot and stripped before any
 * composition or child spawn.
 */
export function renderShimScript(command: string): string {
  return `#!/bin/sh
${SHIM_MARKER}
command -v mxenv >/dev/null 2>&1 || { echo "[mxenv] mxenv not on PATH; reinstall mxenv or run 'mxenv-cli shell-init --remove' to clean up this shim." >&2; exit 127; }
MXENV_SHIM=1 exec mxenv run -- ${command} "$@"
`
}

/** Effective shim list: global ∪ project, deduplicated case-insensitively. */
export function resolveShimCommands(layers: ConfigLayers, includeGlobal = true): string[] {
  const seen = new Set<string>()
  const commands: string[] = []
  const push = (list: unknown) => {
    if (!Array.isArray(list)) return
    for (const entry of list) {
      if (typeof entry !== 'string') continue
      const lower = entry.toLowerCase()
      if (seen.has(lower)) continue
      seen.add(lower)
      commands.push(entry)
    }
  }
  if (includeGlobal) push(layers.global.config.shims)
  push(layers.project.config.shims)
  return commands
}

function readIfExists(path: string): string | null {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}

/**
 * Writes shims for the declared commands and converges the directory: stale
 * tool-generated shims (marker present) whose command is no longer declared
 * are removed. **Handmade files (no marker) are never touched** — a declared
 * command colliding with one is skipped and reported, never overwritten.
 * Idempotent — rewriting an up-to-date shim is skipped byte-for-byte.
 */
export function writeShims(commands: string[], homeDir = homedir()): { written: string[]; removed: string[]; skipped: string[] } {
  const dir = shimsDir(homeDir)
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  const wanted = new Set(commands.map((command) => command.toLowerCase()))
  const written: string[] = []
  const removed: string[] = []
  const skipped: string[] = []

  for (const file of readdirSync(dir)) {
    const path = join(dir, file)
    const content = readIfExists(path)
    if (content === null || !isGeneratedShim(content)) continue
    if (!wanted.has(file.toLowerCase())) {
      rmSync(path)
      removed.push(file)
    }
  }
  for (const command of commands) {
    const path = join(dir, command)
    const content = renderShimScript(command)
    // Never follow a pre-existing symlink: reading/writing through it would
    // touch its target. Replace the link with a regular file instead.
    let isSymlink = false
    try {
      isSymlink = lstatSync(path).isSymbolicLink()
    } catch { /* absent */ }
    const existing = isSymlink ? null : readIfExists(path)
    if (!isSymlink && existing !== null && !isGeneratedShim(existing)) {
      // A handmade file holds the name. Refuse to overwrite; surface it.
      skipped.push(command)
      continue
    }
    if (isSymlink) rmSync(path)
    else if (existing === content) continue
    writeFileSync(path, content, { mode: 0o755 })
    chmodSync(path, 0o755)
    written.push(command)
  }
  return { written, removed, skipped }
}

/** Removes every tool-generated shim; handmade files are left alone. */
export function removeAllShims(homeDir = homedir()): string[] {
  const dir = shimsDir(homeDir)
  if (!existsSync(dir)) return []
  const removed: string[] = []
  for (const file of readdirSync(dir)) {
    const path = join(dir, file)
    const content = readIfExists(path)
    if (content !== null && isGeneratedShim(content)) {
      rmSync(path)
      removed.push(file)
    }
  }
  return removed
}

/**
 * Handmade files that shadow reserved mxenv names would wrap mxenv itself in
 * a shim (weird but terminating) — surface them so the user can delete them.
 */
export function detectHandmadeReservedShims(homeDir = homedir()): string[] {
  const dir = shimsDir(homeDir)
  if (!existsSync(dir)) return []
  const found: string[] = []
  for (const file of readdirSync(dir)) {
    if (!RESERVED_SHIM_NAMES.includes(file.toLowerCase())) continue
    const content = readIfExists(join(dir, file))
    if (content === null || !isGeneratedShim(content)) found.push(file)
  }
  return found
}

/** Infers the rc file from $SHELL; returns null for shells we do not write. */
export function defaultRcPath(shell: string | undefined, homeDir = homedir()): string | null {
  const name = shell ? shell.split('/').pop() : ''
  if (name === 'zsh') return join(homeDir, '.zshrc')
  if (name === 'bash') return join(homeDir, '.bashrc')
  return null
}

/** Atomic write (tmp + rename) so a crash can never truncate a user's rc file. */
function writeFileAtomic(path: string, content: string): void {
  const tmp = `${path}.mxenv-${process.pid}.tmp`
  writeFileSync(tmp, content)
  renameSync(tmp, path)
}

/** Idempotently installs the PATH block; all existing marked blocks are replaced. */
export function upsertRcBlock(rcPath: string, homeDir = homedir()): 'added' | 'updated' | 'unchanged' {
  const existing = readIfExists(rcPath) ?? ''
  const block = rcBlock(homeDir)
  const pattern = rcBlockPattern()
  if (pattern.test(existing)) {
    const replaced = existing.replace(pattern, block)
    if (replaced === existing) return 'unchanged'
    writeFileAtomic(rcPath, replaced.endsWith('\n') ? replaced : `${replaced}\n`)
    return 'updated'
  }
  const separator = existing.length && !existing.endsWith('\n') ? '\n' : ''
  writeFileAtomic(rcPath, `${existing}${separator}${block}\n`)
  return 'added'
}

/** Idempotently removes every marked PATH block, leaving other content intact. */
export function removeRcBlock(rcPath: string): 'removed' | 'absent' {
  const existing = readIfExists(rcPath)
  if (existing === null) return 'absent'
  const pattern = new RegExp(`\\n?${rcBlockPattern().source}\\n?`, 'g')
  if (!pattern.test(existing)) return 'absent'
  writeFileAtomic(rcPath, existing.replace(pattern, '\n'))
  return 'removed'
}

/**
 * Per-command PATH parity: a declared command must resolve to its shim file.
 * `absent` — no executable by that name anywhere on PATH (first install: the
 * shims dir is not on PATH yet); `shadowed` — an earlier PATH entry (volta,
 * another tool) wins and the shim silently never fires. Uses the
 * pre-sanitization PATH captured at boot.
 */
export function findShadowedCommands(commands: string[], originalPath: string | undefined, homeDir = homedir()): { absent: string[]; shadowed: string[] } {
  if (!originalPath) return { absent: [...commands], shadowed: [] }
  const dirs = originalPath.split(delimiter).filter(Boolean)
  const absent: string[] = []
  const shadowed: string[] = []
  for (const command of commands) {
    const shimPath = join(shimsDir(homeDir), command)
    let resolvedTo: string | null = null
    for (const dir of dirs) {
      const candidate = join(dir, command)
      try {
        accessSync(candidate, constants.X_OK)
        resolvedTo = candidate
        break
      } catch { /* not here */ }
    }
    const samePath = (a: string, b: string) =>
      process.platform === 'darwin' ? a.toLowerCase() === b.toLowerCase() : a === b
    if (resolvedTo === null) absent.push(command)
    else if (!samePath(resolvedTo, shimPath)) shadowed.push(command)
  }
  return { absent, shadowed }
}
